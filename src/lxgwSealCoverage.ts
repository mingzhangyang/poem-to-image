export function getLXGWUnlistedCharacters(text: string): string[] {
  return getStampCharacters(text).filter((grapheme) =>
    Array.from(grapheme).some((codePoint) =>
      !LXGW_DOCUMENTED_CODEPOINTS.has(codePoint.codePointAt(0) ?? 0),
    ),
  );
}
